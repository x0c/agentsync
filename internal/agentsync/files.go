const managedMarkerPrefix = "<!-- managed-by: agentsync "

func ensureParent(path string) error {
	return os.MkdirAll(filepath.Dir(path), 0o755)
}

const cursorFrontmatter = `---
description: agentsync global instructions
alwaysApply: true
---
`

func readPayload(path string) ([]byte, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	s := string(data)
	// Strip Cursor frontmatter before comparing a body that begins with the managed marker.
	if strings.HasPrefix(s, "---\n") {
		if body, ok := stripYAMLFrontmatter(s); ok && strings.HasPrefix(body, managedMarkerPrefix) {
			s = body
		}
	}
	if strings.HasPrefix(s, managedMarkerPrefix) {
		if idx := strings.Index(s, "-->\n"); idx >= 0 {
			return []byte(s[idx+4:]), nil
		}
	}
	return []byte(s), nil
}

func stripYAMLFrontmatter(s string) (string, bool) {
	if !strings.HasPrefix(s, "---\n") {
		return "", false
	}
	rest := s[4:]
	idx := strings.Index(rest, "\n---\n")
	if idx < 0 {
		return "", false
	}
	return rest[idx+5:], true
}

func sameContent(a, b string) bool {
	aa, err := readPayload(a)
	if err != nil {
		return false
	}
	bb, err := readPayload(b)
	if err != nil {
		return false
	}
	return string(aa) == string(bb)
}

// isManagedAgentsyncFile identifies copies generated by agentsync, including Cursor rules.
// These files derive from the canonical source rather than independent user content.
// Replace stale copies directly; never append their old body back into the source.
func isManagedAgentsyncFile(path string) bool {
	data, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	s := string(data)
	if strings.HasPrefix(s, "---\n") {
		if body, ok := stripYAMLFrontmatter(s); ok {
			s = body
		}
	}
	return strings.HasPrefix(s, managedMarkerPrefix)
}

func writeManagedCopy(source, target string) error {
	data, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	return writeManagedCopyBytes(source, target, data, "")
}

// managedCopyBody prefixes payload with the generated-file marker. The hash
// covers the exact bytes written after the marker, so editing either the source
// or a runtime overlay invalidates the copy.
func managedCopyBody(source string, payload []byte, overlay string) []byte {
	sum := sha256.Sum256(payload)
	var b strings.Builder
	switch overlay {
	case "":
		fmt.Fprintf(&b, "%ssource=%q sha256=%s -->\n", managedMarkerPrefix, source, hex.EncodeToString(sum[:]))
	default:
		fmt.Fprintf(&b, "%ssource=%q sha256=%s %s%q -->\n", managedMarkerPrefix, source, hex.EncodeToString(sum[:]), overlayMarkerAttr, overlay)
	}
	b.Write(payload)
	return []byte(b.String())
}

func writeManagedCopyBytes(source, target string, payload []byte, overlay string) error {
	if err := ensureParent(target); err != nil {
		return err
	}
	return os.WriteFile(target, managedCopyBody(source, payload, overlay), 0o644)
}

func writeCursorRuleBytes(source, target string, payload []byte, overlay string) error {
	if err := ensureParent(target); err != nil {
		return err
	}
	return os.WriteFile(target, cursorRuleBody(source, payload, overlay), 0o644)
}

// cursorRuleBody adds the alwaysApply frontmatter Cursor requires, then the
// generated-file marker and the instruction body.
func cursorRuleBody(source string, payload []byte, overlay string) []byte {
	var b strings.Builder
	b.WriteString(cursorFrontmatter)
	b.Write(managedCopyBody(source, payload, overlay))
	return []byte(b.String())
}

// samePayload reports whether an existing target already holds payload after
// stripping generated headers and Cursor frontmatter.
func samePayload(path string, payload []byte) bool {
	got, err := readPayload(path)
	if err != nil {
		return false
	}
	return bytes.Equal(got, payload)
}

// managedCopyOverlay returns the runtime recorded in a generated copy's marker,
// or the empty string for a copy rendered from the source alone. It separates a
// copy created for an overlay, which must revert to a symlink once the overlay
// disappears, from a copy that is the platform's link fallback.
func managedCopyOverlay(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	s := string(data)
	if strings.HasPrefix(s, "---\n") {
		if body, ok := stripYAMLFrontmatter(s); ok {
			s = body
		}
	}
	if !strings.HasPrefix(s, managedMarkerPrefix) {
		return ""
	}
	line, _, _ := strings.Cut(s, "\n")
	idx := strings.Index(line, overlayMarkerAttr)
	if idx < 0 {
		return ""
	}
	quoted := line[idx+len(overlayMarkerAttr):]
	if len(quoted) == 0 || quoted[0] != '"' {
		return ""
	}
	for end := 1; end < len(quoted); end++ {
		if quoted[end] != '"' {
			continue
		}
		value, err := strconv.Unquote(quoted[:end+1])
		if err != nil {
			return ""
		}
		return value
	}
	return ""
}

func createAlias(source, target, mode string, render instructionRender) (string, error) {
	if err := ensureParent(target); err != nil {
		return "", err
	}
	// Cursor global rules require alwaysApply frontmatter rather than a bare AGENTS.md symlink.
	if mode == "cursor" {
		if err := writeRenderedCursorRule(source, target, render); err != nil {
			return "", err
		}
		return "cursor-rule", nil
	}
	// A runtime overlay cannot live behind a symlink, so the merged body is
	// written as a managed copy that the next run can refresh idempotently.
	if render.active() {
		payload, err := render.body(source)
		if err != nil {
			return "", err
		}
		if err := writeManagedCopyBytes(source, target, payload, render.Runtime); err != nil {
			return "", err
		}
		return "managed-copy", nil
	}
	// Directory aliases (skill roots) never fall back to a static copy:
	// on Windows try a symlink, then an NTFS junction, then fail with
	// Developer Mode guidance. File aliases keep the symlink, hardlink,
	// managed-copy order.
	if isDirectorySource(source) {
		return createDirAlias(source, target, mode)
	}
	return createFileAlias(source, target, mode)
}

func writeRenderedCursorRule(source, target string, render instructionRender) error {
	payload, err := render.body(source)
	if err != nil {
		return err
	}
	return writeCursorRuleBytes(source, target, payload, render.Runtime)
}

// createDirAlias links a directory source. Junctions apply only on Windows
// and only to directories.
func createDirAlias(source, target, mode string) (string, error) {
	linkTarget := source
	if mode == "relative-link" {
		rel, err := filepath.Rel(filepath.Dir(target), source)
		if err == nil {
			linkTarget = rel
		}
	}
	symlinkErr := symlinkCreateFunc(linkTarget, target)
	if symlinkErr == nil {
		return "symlink", nil
	}
	// Junction fallback: on Windows this creates a real NTFS junction; off
	// Windows createJunction fails, and tests may override junctionCreateFunc
	// to verify the fallback order on every OS.
	junctionSource := source
	if !filepath.IsAbs(junctionSource) {
		if abs, absErr := filepath.Abs(junctionSource); absErr == nil {
			junctionSource = abs
		}
	}
	if err := junctionCreateFunc(junctionSource, target); err == nil {
		return "junction", nil
	} else if runtime.GOOS == "windows" {
		return "", developerModeError(target, symlinkErr, err)
	} else {
		// Off Windows there is no junction fallback; surface the symlink
		// error instead of attempting a file-only managed copy of a directory.
		return "", fmt.Errorf("cannot create directory alias for %s: symbolic link failed: %w", target, symlinkErr)
	}
}

func createFileAlias(source, target, mode string) (string, error) {
	linkTarget := source
	if mode == "relative-link" {
		rel, err := filepath.Rel(filepath.Dir(target), source)
		if err == nil {
			linkTarget = rel
		}
	}
	if err := symlinkCreateFunc(linkTarget, target); err == nil {
		return "symlink", nil
	}
	if runtime.GOOS == "windows" {
		if err := os.Link(source, target); err == nil {
			return "hardlink", nil
		}
	}
	if err := writeManagedCopy(source, target); err != nil {
		return "", err
	}
	return "copy", nil
}

func removePath(path string) error {
	info, err := os.Lstat(path)
	if err != nil {
		return err
	}
	if info.IsDir() {
		return fmt.Errorf("refusing to remove directory %s", path)
	}
	return os.Remove(path)
}

func backupFile(path string) (string, error) {
	if !pathExists(path) {
		return "", nil
	}
	info, err := os.Lstat(path)
	if err != nil {
		return "", err
	}
	// Managed links (symlinks and junctions) are backed up as their target
	// string, never as directory contents. Check links before IsDir so a
	// junction is never copied as a directory.
	if isManagedLink(info) {
		kind := linkKind(info)
		target, err := os.Readlink(path)
		if err != nil {
			return "", fmt.Errorf("unsupported link at %s: %w", path, err)
		}
		stampDir, err := backupStampDir()
		if err != nil {
			return "", err
		}
		name, existing, err := backupPayloadName(stampDir, path, kind)
		if err != nil {
			return "", err
		}
		dst := filepath.Join(stampDir, name)
		if existing {
			return dst, nil
		}
		if err := writeNewBackupFile(dst, []byte(target+"\n"), 0o644); err != nil {
			return "", err
		}
		if err := recordBackupEntryAt(stampDir, path, name, kind); err != nil {
			return "", errors.Join(err, os.Remove(dst))
		}
		return dst, nil
	}
	if info.IsDir() {
		return "", fmt.Errorf("refusing to back up directory %s", path)
	}
	stampDir, err := backupStampDir()
	if err != nil {
		return "", err
	}
	kind := "file"
	name, existing, err := backupPayloadName(stampDir, path, kind)
	if err != nil {
		return "", err
	}
	dst := filepath.Join(stampDir, name)
	if existing {
		return dst, nil
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	if err := writeNewBackupFile(dst, data, info.Mode().Perm()); err != nil {
		return "", err
	}
	if err := recordBackupEntryAt(stampDir, path, name, kind); err != nil {
		return "", errors.Join(err, os.Remove(dst))
	}
	return dst, nil
}

func backupAny(path string) (string, error) {
	if !pathExists(path) {
		return "", nil
	}
	info, err := os.Lstat(path)
	if err != nil {
		return "", err
	}
	// Back up junctions as links, never as directory contents.
	if isManagedLink(info) {
		return backupFile(path)
	}
	if !info.IsDir() {
		return backupFile(path)
	}
	stampDir, err := backupStampDir()
	if err != nil {
		return "", err
	}
	name, existing, err := backupPayloadName(stampDir, path, "dir")
	if err != nil {
		return "", err
	}
	dst := filepath.Join(stampDir, name)
	if existing {
		return dst, nil
	}
	// Reserve a new directory; never merge into another entry's payload.
	if err := os.Mkdir(dst, info.Mode().Perm()); err != nil {
		return "", err
	}
	if err := copyDir(path, dst); err != nil {
		return "", errors.Join(err, os.RemoveAll(dst))
	}
	if err := recordBackupEntryAt(stampDir, path, name, "dir"); err != nil {
		return "", errors.Join(err, os.RemoveAll(dst))
	}
	return dst, nil
}

func writeNewBackupFile(path string, data []byte, perm os.FileMode) (err error) {
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, perm)
	if err != nil {
		return err
	}
	_, writeErr := file.Write(data)
	err = errors.Join(writeErr, file.Close())
	if err != nil {
		err = errors.Join(err, os.Remove(path))
	}
	return err
}

func copyDir(src, dst string) error {
	return filepath.WalkDir(src, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		info, err := os.Lstat(path)
		if err != nil {
			return err
		}
		if d.IsDir() {
			return os.MkdirAll(target, info.Mode().Perm())
		}
		if isManagedLink(info) {
			linkTarget, err := os.Readlink(path)
			if err != nil {
				return err
			}
			if err := ensureParent(target); err != nil {
				return err
			}
			if err := symlinkCreateFunc(linkTarget, target); err == nil {
				return nil
			} else if runtime.GOOS != "windows" {
				return err
			}
			// On Windows, preserve directory junctions when the link target
			// is a directory; file links fall back to the symlink error.
			if targetInfo, statErr := os.Stat(linkTarget); statErr == nil && targetInfo.IsDir() {
				absTarget := linkTarget
				if !filepath.IsAbs(absTarget) {
					absTarget = filepath.Join(filepath.Dir(path), linkTarget)
				}
				if abs, absErr := filepath.Abs(absTarget); absErr == nil {
					absTarget = abs
				}
				return junctionCreateFunc(absTarget, target)
			} else if !filepath.IsAbs(linkTarget) {
				absTarget := filepath.Join(filepath.Dir(path), linkTarget)
				if targetInfo, statErr := os.Stat(absTarget); statErr == nil && targetInfo.IsDir() {
					return junctionCreateFunc(absTarget, target)
				}
			}
			return err
		}
		if !info.Mode().IsRegular() {
			return nil
		}
		return copyFile(path, target, info.Mode().Perm())
	})
}

func writeFileAtomic(path string, data []byte, perm os.FileMode) error {
	if err := ensureParent(path); err != nil {
		return err
	}
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".agentsync-tmp-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	cleanup := true
	defer func() {
		if cleanup {
			_ = os.Remove(tmpName)
		}
	}()
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Chmod(perm); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpName, path); err != nil {
		return err
	}
	cleanup = false
	return nil
}

func copyFile(src, dst string, perm os.FileMode) (err error) {
	if err := ensureParent(dst); err != nil {
		return err
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, in.Close()) }()
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, perm)
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, out.Close()) }()
	_, err = io.Copy(out, in)
	return err
}

func sanitizePath(path string) string {
	path = filepath.Clean(path)
	path = strings.TrimPrefix(path, string(filepath.VolumeName(path)))
	path = strings.TrimLeft(path, string(filepath.Separator))
	replacer := strings.NewReplacer("/", "__", "\\", "__", ":", "_")
	return replacer.Replace(path)
}
